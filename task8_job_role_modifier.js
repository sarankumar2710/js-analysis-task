// Concepts: replace, startsWith, endsWith
// ============================================================


// ============================================================
// SECTION 1 – replace() (Task 1)
// ============================================================

let role = "python developer";

// 1. Replace "python" with "javascript"
let newRole = role.replace("python", "javascript");
console.log("New Role:", newRole); // javascript developer


// ============================================================
// SECTION 2 – startsWith() (Task 2)
// ============================================================

// 2. Check if role starts with "python"
let starts = role.startsWith("python");
console.log("Starts with python:", starts); // true


// ============================================================
// SECTION 3 – endsWith() (Task 3)
// ============================================================

// 3. Check if role ends with "developer"
let ends = role.endsWith("developer");
console.log("Ends with developer:", ends); // true
